package io.silvicky.item_br.worldgen.abyss;

import io.silvicky.item.backrooms.AbyssWindow;
import io.silvicky.item.worldgen.CustomRule;
import net.minecraft.resources.Identifier;
import net.minecraft.util.RandomSource;
import net.minecraft.world.level.ChunkPos;
import net.minecraft.world.level.block.Blocks;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraft.world.level.chunk.ChunkAccess;
import net.minecraft.world.level.levelgen.RandomState;
import org.jspecify.annotations.NonNull;

/**
 * One layer of the Abyss demo: a floor, a ceiling, and a pattern of pillars.
 *
 * <p>Each layer is a real dimension generated by this rule. The rule only writes between {@code y = 0} and
 * {@code y = LAYER_HEIGHT - 1}, so the same code serves any layer index and any {@link AbyssWindow#LAYER_HEIGHT}.
 *
 * <p>Every layer is visually distinct: its own floor, shell, pillar material, light source and pillar
 * pattern, so a descent reads as moving between places rather than repeating one tile. The five layers are
 * grey deepslate, gold-flecked blackstone, teal prismarine, purple purpur and bone-white deepdark.
 *
 * <h2>The hole</h2>
 *
 * <p>{@link AbyssDecayRule} is consulted first, and a chunk it rejects is left completely empty. Its rule is
 * "decay inside four chunks of the origin", so every layer leaves the same 7x7 chunks as air and the result
 * is a shaft straight through the whole stack. That shaft is how the demo is travelled: fall in at the top,
 * and the window carries you down through the layers.
 *
 * <p>It also uses the same rule the existing {@code br:abyss} world uses, so the hole has exactly the shape
 * that world already has - one rule, one hole, no second definition to drift.
 */
public class AbyssLayerRule implements CustomRule
{
    /** Shared instance: the decay rule is stateless. */
    private static final AbyssDecayRule HOLE = new AbyssDecayRule();

    /** Floor surface, one per layer. */
    private static final BlockState[] FLOOR = {
            Blocks.DEEPSLATE_TILES.defaultBlockState(),
            Blocks.BLACKSTONE.defaultBlockState(),
            Blocks.DARK_PRISMARINE.defaultBlockState(),
            Blocks.PURPUR_BLOCK.defaultBlockState(),
            Blocks.SCULK.defaultBlockState()
    };

    /** Walls and ceiling. */
    private static final BlockState[] SHELL = {
            Blocks.DEEPSLATE.defaultBlockState(),
            Blocks.BASALT.defaultBlockState(),
            Blocks.PRISMARINE_BRICKS.defaultBlockState(),
            Blocks.OBSIDIAN.defaultBlockState(),
            Blocks.DEEPSLATE_BRICKS.defaultBlockState()
    };

    /** Pillars. The one thing a player sees most of, so this is what makes a layer recognisable. */
    private static final BlockState[] PILLAR = {
            Blocks.POLISHED_DEEPSLATE.defaultBlockState(),
            Blocks.GILDED_BLACKSTONE.defaultBlockState(),
            Blocks.PRISMARINE.defaultBlockState(),
            Blocks.PURPUR_PILLAR.defaultBlockState(),
            Blocks.BONE_BLOCK.defaultBlockState()
    };

    /** Light on top of each pillar, matching the layer's palette. */
    private static final BlockState[] LIGHT = {
            Blocks.GLOWSTONE.defaultBlockState(),
            Blocks.SHROOMLIGHT.defaultBlockState(),
            Blocks.SEA_LANTERN.defaultBlockState(),
            Blocks.PEARLESCENT_FROGLIGHT.defaultBlockState(),
            Blocks.VERDANT_FROGLIGHT.defaultBlockState()
    };

    private final int layer;
    private final BlockState floor;
    private final BlockState shell;
    private final BlockState pillar;
    private final BlockState light;
    private final Identifier randomKey;

    public AbyssLayerRule(int layer)
    {
        this.layer = layer;
        this.floor = FLOOR[layer % FLOOR.length];
        this.shell = SHELL[layer % SHELL.length];
        this.pillar = PILLAR[layer % PILLAR.length];
        this.light = LIGHT[layer % LIGHT.length];
        //Per-layer, so two layers do not draw the same accents from the same stream.
        this.randomKey = Identifier.fromNamespaceAndPath("silvicky", "abyss_layer_" + layer);
    }

    @Override
    public void gen(@NonNull ChunkAccess chunk, @NonNull RandomState randomState)
    {
        //The hole. Leave the chunk untouched (all air) and the shaft runs through this layer too.
        if (HOLE.decay(chunk.getPos(), randomState)) return;

        ChunkPos pos = chunk.getPos();
        int ceiling = AbyssWindow.LAYER_HEIGHT - 4;

        for (int x = 0; x < 16; x++)
        {
            for (int z = 0; z < 16; z++)
            {
                //Floor: three blocks of shell with the layer's own surface on top.
                for (int y = 0; y < 4; y++)
                    chunk.setBlockState(pos.getBlockAt(x, y, z), y == 3 ? floor : shell);

                //Ceiling: four blocks at the very top, so a layer is closed except where the shaft is.
                for (int y = ceiling; y < AbyssWindow.LAYER_HEIGHT; y++)
                    chunk.setBlockState(pos.getBlockAt(x, y, z), shell);
            }
        }

        RandomSource random = randomState.getOrCreateRandomFactory(randomKey).at(pos.x(), 0, pos.z());
        switch (layer % 5)
        {
            case 0 -> column(chunk, pos, 0, 0);                       //one corner pillar
            case 1 ->                                                  //a cross through the middle
            {
                for (int i = 0; i < 16; i++)
                {
                    column(chunk, pos, i, 7);
                    column(chunk, pos, 7, i);
                }
            }
            case 2 ->                                                  //a forest, on a jittered grid
            {
                for (int gx = 0; gx < 4; gx++)
                {
                    for (int gz = 0; gz < 4; gz++)
                        column(chunk, pos, gx * 4 + random.nextInt(3), gz * 4 + random.nextInt(3));
                }
            }
            case 3 ->                                                  //a ring around the chunk edge
            {
                for (int i = 2; i < 14; i += 3)
                {
                    column(chunk, pos, i, 2);
                    column(chunk, pos, i, 13);
                    column(chunk, pos, 2, i);
                    column(chunk, pos, 13, i);
                }
            }
            default ->                                                 //a lone obelisk, off centre
            {
                int x = 4 + random.nextInt(8);
                int z = 4 + random.nextInt(8);
                column(chunk, pos, x, z);
                //A wider base, so it reads as architecture rather than a fence post.
                for (int y = 4; y < 8; y++)
                {
                    for (int dx = -1; dx <= 1; dx += 2)
                        for (int dz = -1; dz <= 1; dz += 2)
                            chunk.setBlockState(pos.getBlockAt(x + dx, y, z + dz), pillar);
                }
            }
        }
    }

    /** A full-height pillar with its light at the top. Coordinates are chunk-local and may be added to. */
    private void column(ChunkAccess chunk, ChunkPos pos, int x, int z)
    {
        if (x < 0 || x > 15 || z < 0 || z > 15) return;
        for (int y = 4; y < AbyssWindow.LAYER_HEIGHT - 4; y++)
            chunk.setBlockState(pos.getBlockAt(x, y, z), pillar);
        chunk.setBlockState(pos.getBlockAt(x, AbyssWindow.LAYER_HEIGHT - 5, z), light);
    }

    @Override
    public String name()
    {
        return "abyss_layer_" + layer;
    }
}
