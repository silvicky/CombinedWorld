/**
 * A vertical window over a stack of layers: the demo of "concatenate worlds along Y".
 *
 * <h2>What is real and what is shown</h2>
 *
 * <p>There are {@link #LAYERS} real dimensions ({@code abyss:layer0} .. {@code abyss:layer4}), each
 * {@link #LAYER_HEIGHT} blocks tall and each generated by its own rule. A player is always physically in one
 * of them, at that layer's own Y. The client is told something else entirely: that the dimension is
 * {@link #WINDOW_HEIGHT} tall, and it is sent chunks assembled from {@link #WINDOW_LAYERS} consecutive
 * layers.
 *
 * <p>The client therefore works in <b>window coordinates</b>, and the two coordinate systems are related by a
 * whole number of layers:
 *
 * <pre>
 *   clientY = serverY + WINDOW_MIN_Y + band * LAYER_HEIGHT
 *   band    = layer - anchor
 * </pre>
 *
 * <p>{@code WINDOW_MIN_Y} is kept as a constant even though the demo's window now fits at 0, because the
 * value is not free: {@code DimensionType} rejects {@code min_y + height > 2032}. Three 1024-tall layers
 * cannot start at 0 and need {@code min_y = -1040}; three 64-tall layers fit anywhere. Folding the constant
 * into every offset below is what lets the layer height change without touching the conversion code.
 *
 * <p>{@code anchor} is the layer shown in the bottom band. It is per player, because two players on
 * different layers need different windows. Everything that crosses the wire is converted at the boundary:
 * packets out add the offset, packets in subtract it. That is the whole protocol cost - one add or subtract
 * per coordinate, the same shape as the X/Z shuffle in {@link VecTransformer}, except that the offset changes
 * only when the window slides instead of on every border crossing.
 *
 * <h2>Why the window slides</h2>
 *
 * <p>A player descending from layer {@code k} to {@code k-1} is teleported one layer up (from Y ~ 0 to
 * Y ~ LAYER_HEIGHT - 1). Because the layer also changed, the offset changes by exactly -LAYER_HEIGHT and the
 * client sees a one-block step. That works only while the destination layer is inside the window, so the
 * window follows the player: it is centred on them, with one layer visible below and one above, and it slides
 * by one layer whenever they reach its top or bottom band. The slide is a chunk re-send plus one position
 * packet, and it is visually silent because the world and the player move together by the same
 * LAYER_HEIGHT blocks - the bands shift down while the player's own band index drops by one.
 *
 * <p>The two slides are the same operation with opposite signs, and both are needed: the window originally
 * slid downward only, which left the layer above the player permanently out of view.
 *
 * <p>This class is the arithmetic and the seam handling. The pixels come from
 * {@link AbyssChunkComposer}.
 */
public final class AbyssWindow
{
    /**
     * Height of one concatenated layer. A multiple of 16, as every dimension height must be.
     *
     * <p>64 for the demo, which makes a window 192 tall and a layer four sections deep - small enough to
     * read the whole stack in one screen and cheap enough that a bad composition is obvious immediately.
     * Nothing in this class depends on the value beyond the constants below.
     */
    public static final int LAYER_HEIGHT = 64;
    /** How many layers are stacked. */
    public static final int LAYERS = 5;
    /** How many of them the client is shown at once. */
    public static final int WINDOW_LAYERS = 3;
    /** Height the client is told the dimension has. */
    public static final int WINDOW_HEIGHT = LAYER_HEIGHT * WINDOW_LAYERS;

    /**
     * Lowest Y of the window the client is told about.
     *
     * <p>0 here, and free to be so: {@code DimensionType}'s constructor rejects
     * {@code minY + height > MAX_Y + 1} with {@code MAX_Y = 2031}, and 192 fits comfortably. The value only
     * has to move below zero if {@link #LAYER_HEIGHT} ever grows past ~677; the arithmetic is written so that
     * changing it is a one-line edit.
     *
     * <p>The layers themselves keep {@code min_y 0}, so a layer's own Y and the window's Y differ by a whole
     * number of layers plus this constant. That constant is folded into {@link #bandOffset}, which is the only
     * place the difference is written down.
     */
    public static final int WINDOW_MIN_Y = 0;
    public static final int SECTIONS_PER_LAYER = LAYER_HEIGHT / 16;
    public static final int WINDOW_SECTIONS = WINDOW_HEIGHT / 16;
    /** Section index of the window's first section. Light masks are indexed relative to it. */
    public static final int WINDOW_MIN_SECTION = WINDOW_MIN_Y / 16;

    /**
     * How close to the window's edge the player may get before the window slides, in blocks.
     *
     * <p>The slide is not invisible on its own - it moves the player 64 blocks in the client's coordinates.
     * It is invisible because the bands move with them: the player's own layer is re-sent one band higher at
     * exactly the moment their client position moves one layer up, so terrain and camera shift together. Doing
     * it a few blocks before the seam rather than at the seam means the seam crossing itself carries no re-send
     * at all: there the band changes by one and the layer changes by one, and the two cancel exactly.
     *
     * <p>Small on purpose. A larger buffer is more time for the newly admitted layer to generate, at the price
     * of holding a window that is increasingly centred away from the player; {@link #healIncomplete} covers the
     * loading side of that trade either way.
     */
    public static final int SLIDE_BUFFER = 4;

    /**
     * The dimension type sent in login and respawn packets instead of the layer's own.
     *
     * <p>The layer levels really are 1024 tall; the client must believe 3072, because that is how many
     * sections it will accept per chunk. The type is a datapack entry, so it is in the synced registry and
     * the client can resolve this id without any extra mod channel.
     */
    public static final Identifier WINDOW_TYPE = Identifier.parse("silvicky:abyss_window");

    /**
     * The dimension key the client is told it is in, for every layer.
     *
     * <p>One constant id, so the client shows a single dimension whose name never changes, and so a seam
     * teleport is a teleport rather than a dimension change. Nothing on the server uses this key - the layers
     * keep their real ids - but the client resolves its whole level from the spawn info it is given, and
     * {@code ClientPacketListener.handleRespawn} compares the announced key with the current level's key by
     * reference. Sending the same interned key every time therefore keeps the existing {@code ClientLevel}
     * and its chunk cache instead of rebuilding them.
     */
    public static final Identifier WINDOW_DIMENSION = Identifier.parse("abyss:window");

    public static ResourceKey<Level> windowKey()
    {
        return ResourceKey.create(Registries.DIMENSION, WINDOW_DIMENSION);
    }

    private static final String NAMESPACE = "abyss";

    private static final List<ResourceKey<Level>> LAYER_KEYS;

    static
    {
        //DimensionType's own constructor enforces exactly this, and a violation there shows up as a datapack
        //error naming the JSON rather than the constant that caused it. Fail here instead, where the number is.
        if (WINDOW_MIN_Y % 16 != 0)
            throw new IllegalStateException("abyss window min_y must be a multiple of 16");
        if (WINDOW_MIN_Y < DimensionType.MIN_Y || WINDOW_MIN_Y + WINDOW_HEIGHT > DimensionType.MAX_Y + 1)
            throw new IllegalStateException("abyss window does not fit DimensionType's Y range: min_y "
                                                    + WINDOW_MIN_Y + ", height " + WINDOW_HEIGHT);

        List<ResourceKey<Level>> keys = new ArrayList<>(LAYERS);
        for (int i = 0; i < LAYERS; i++)
            keys.add(ResourceKey.create(Registries.DIMENSION, Identifier.fromNamespaceAndPath(NAMESPACE, "layer" + i)));
        LAYER_KEYS = List.copyOf(keys);
    }

    /** Per-player window anchor. Concurrent because packet hooks read it off the server thread too. */
    private static final Map<ServerPlayer, Integer> anchors = new ConcurrentHashMap<>();
    /** Whether the player has already been sent a complete window since the last anchor change. */
    private static final Map<ServerPlayer, Boolean> ready = new ConcurrentHashMap<>();
    /** Where the last loading tickets were placed, so a stationary player does not add one per tick. */
    private static final Map<ServerPlayer, TicketKey> tickets = new ConcurrentHashMap<>();
    /**
     * Columns whose composition was missing a band when it was last sent.
     *
     * <p>The client is only ever told about a chunk when the server marks it pending, so a column sent while
     * one of its bands was still generating keeps its air band until something asks for it again. Nothing does:
     * the player's own chunk has not moved, so vanilla's tracking diff never runs. Filled in by
     * {@link AbyssChunkComposer} at send time, drained by {@link #healIncomplete}.
     */
    private static final Map<ServerPlayer, java.util.Set<ChunkPos>> incomplete = new ConcurrentHashMap<>();
    /** Tick counter per player, for the retry sweep. */
    private static final Map<ServerPlayer, Integer> ticks = new ConcurrentHashMap<>();
    /** Players currently being moved across a layer seam, so the respawn packet can be suppressed. */
    private static final Set<ServerPlayer> seamTeleports = ConcurrentHashMap.newKeySet();
    /**
     * Layer columns that finished loading, waiting to be handled on the server thread.
     *
     * <p><b>This queue exists because the chunk-load event is not on the server thread.</b> Fabric fires
     * {@code ServerChunkEvents.CHUNK_LOAD} from {@code ChunkStatusTasksMixin}, i.e. from inside the chunk-status
     * task chain, and the handler used to call {@code PlayerChunkSender.markChunkPendingToSend} straight from
     * there. That mutates {@code pendingChunks}, an unsynchronised {@code LongOpenHashSet} which the server
     * thread is walking in {@code sendNextChunks} at the same time. A lost insert there is a chunk the client
     * is never told about, and it shows up exactly as the reported symptom: an adjacent layer that stays empty
     * until something else happens to re-send it.
     *
     * <p>So the event handler now only records, and the server thread drains. Recording into a concurrent set
     * also coalesces the burst of loads that one view produces - five layers of the same column, eight chunk
     * loads each, all wanting the same re-send.
     */
    private static final Set<LayerColumn> loadedColumns = ConcurrentHashMap.newKeySet();

    private record LayerColumn(int layer, ChunkPos pos) {}
    private record TicketKey(ChunkPos pos, int anchor, int radius) {}

    private AbyssWindow() {}

    public static List<ResourceKey<Level>> layerKeys()
    {
        return LAYER_KEYS;
    }

    public static ResourceKey<Level> layerKey(int layer)
    {
        return LAYER_KEYS.get(layer);
    }

    /** Layer index of a level, or -1 when this level is not part of the stack. */
    public static int layerIndex(@Nullable Level level)
    {
        return level == null ? -1 : layerIndex(level.dimension());
    }

    /**
     * Layer index of a level key, or -1 when it is not part of the stack.
     *
     * <p>The key comes from the packet, not from the player, and that matters for the login and respawn
     * packets: they announce the level the client is about to switch to, which is not necessarily the level
     * the server object has been moved to yet. Reading the key the packet already carries removes the ordering
     * question entirely - and it is the only value the client will build its level from.
     */
    public static int layerIndex(@Nullable ResourceKey<Level> key)
    {
        return key == null ? -1 : layerIndex(key.identifier());
    }

    private static int layerIndex(Identifier id)
    {
        if (!NAMESPACE.equals(id.getNamespace())) return -1;
        String path = id.getPath();
        if (!path.startsWith("layer")) return -1;
        try
        {
            int index = Integer.parseInt(path.substring("layer".length()));
            return index >= 0 && index < LAYERS ? index : -1;
        }
        catch (NumberFormatException e)
        {
            return -1;
        }
    }

    public static int layerIndex(@Nullable ServerPlayer player)
    {
        return player == null ? -1 : layerIndex(player.level());
    }

    /** Whether this player is in a windowed layer, and so needs every packet converted. */
    public static boolean handles(@Nullable ServerPlayer player)
    {
        return layerIndex(player) >= 0;
    }

    @Nullable
    public static ServerLevel layer(@Nullable MinecraftServer server, int layer)
    {
        if (server == null || layer < 0 || layer >= LAYERS) return null;
        return server.getLevel(LAYER_KEYS.get(layer));
    }

    /** Bottom layer of the window this player is currently shown. */
    public static int anchor(ServerPlayer player)
    {
        Integer stored = anchors.get(player);
        return stored == null ? initialAnchor(layerIndex(player)) : stored;
    }

    /** Start a window with the player in its top band, so two layers are already visible below them. */
    /**
     * Start with the player in the middle band, so there is one layer visible below and one above.
     *
     * <p>It used to be the top band, which made the window look downward only: the layer below was visible and
     * the layer above was not part of the window at all. Near the ends of the stack the clamp wins, because
     * there is genuinely nothing below layer 0 or above the last layer.
     */
    public static int initialAnchor(int layer)
    {
        return Mth.clamp(layer - (WINDOW_LAYERS / 2), 0, LAYERS - WINDOW_LAYERS);
    }

    /** Which band of the window the player's layer occupies: 0 bottom, 1 middle, 2 top. */
    public static int band(ServerPlayer player)
    {
        int layer = layerIndex(player);
        return layer < 0 ? 0 : layer - anchor(player);
    }

    /** Whole-block distance between the player's layer Y and the window Y at the bottom of their band. */
    public static int bandBlockOffset(ServerPlayer player)
    {
        return WINDOW_MIN_Y + band(player) * LAYER_HEIGHT;
    }

    public static double bandOffset(ServerPlayer player)
    {
        return bandBlockOffset(player);
    }

    public static double clientY(ServerPlayer player)
    {
        return player.getY() + bandOffset(player);
    }

    public static Vec3 toClient(ServerPlayer player, Vec3 serverPos)
    {
        return serverPos.add(0, bandOffset(player), 0);
    }

    public static BlockPos toClient(ServerPlayer player, BlockPos serverPos)
    {
        return serverPos.offset(0, bandBlockOffset(player), 0);
    }

    public static SectionPos toClient(ServerPlayer player, SectionPos serverPos)
    {
        return SectionPos.of(serverPos.x(), serverPos.y() + bandBlockOffset(player) / 16, serverPos.z());
    }

    /** A Y the client sent, turned back into the layer's own coordinate. */
    public static double toServerY(ServerPlayer player, double clientY)
    {
        return clientY - bandOffset(player);
    }

    public static Vec3 toServer(ServerPlayer player, Vec3 clientPos)
    {
        return clientPos.add(0, -bandOffset(player), 0);
    }

    public static BlockPos toServer(ServerPlayer player, BlockPos clientPos)
    {
        return clientPos.offset(0, -bandBlockOffset(player), 0);
    }

    public static void forget(ServerPlayer player)
    {
        if (player == null) return;
        TicketKey key = tickets.remove(player);
        if (key != null) releaseTickets(player, key);
        anchors.remove(player);
        ready.remove(player);
        incomplete.remove(player);
        ticks.remove(player);
        seamTeleports.remove(player);
    }
    /** Records that a composed column went out with at least one band still missing. */
    public static void markIncomplete(ServerPlayer player, ChunkPos pos)
    {
        incomplete.computeIfAbsent(player, p -> ConcurrentHashMap.newKeySet()).add(pos);
    }

    /**
     * Whether this player is being moved across a seam right now.
     *
     * <p>The seam is a teleport between two real levels, but the client is looking at one constant dimension,
     * so the respawn packet vanilla sends would only rebuild its {@code LocalPlayer} and flash the loading
     * screen. The packet is sent synchronously inside {@code ServerPlayer.teleport}, so a flag set around that
     * call is enough - and it is deliberately a flag rather than "both levels are layers", because a death
     * respawn inside a layer must still go through.
     */
    public static boolean isSeamTeleport(ServerPlayer player)
    {
        return seamTeleports.contains(player);
    }

    /**
     * One tick of housekeeping for the whole server: drain the chunk-load queue, then each player's window.
     *
     * <p>Runs at the <b>start</b> of the server tick, before player ticks. That ordering is what makes a slide
     * clean: the position packet goes out first and every chunk packet sent later in the same tick is composed
     * with the new anchor, so no packet can cross the slide carrying the old band.
     *
     * <p>Must run on the server thread.
     */
    public static void tick(MinecraftServer server)
    {
        drainLoadedColumns(server);
        for (ServerPlayer player : server.getPlayerList().getPlayers()) tickPlayer(player);
    }

    /**
     * Turns recorded chunk loads into re-sends, on the server thread.
     *
     * <p>The host column is normally sent when the <em>player's own</em> layer chunk is ready, which says
     * nothing about the other bands: they may still be generating. Composition runs at send time, pads a
     * missing band with air, and nothing asks for the column again while the player's own chunk stays put.
     * This is what asks again.
     */
    private static void drainLoadedColumns(MinecraftServer server)
    {
        if (loadedColumns.isEmpty()) return;
        List<LayerColumn> batch = new ArrayList<>(loadedColumns);
        loadedColumns.clear();

        for (ServerPlayer player : server.getPlayerList().getPlayers())
        {
            if (!handles(player) || player.connection == null) continue;
            int anchor = anchor(player);
            ServerLevel host = (ServerLevel) player.level();
            for (LayerColumn loaded : batch)
            {
                if (loaded.layer() < anchor || loaded.layer() >= anchor + WINDOW_LAYERS) continue;
                ChunkPos pos = loaded.pos();
                if (!player.getChunkTrackingView().contains(pos)) continue;
                LevelChunk chunk = host.getChunkSource().getChunkNow(pos.x(), pos.z());
                if (chunk == null) continue;
                player.connection.chunkSender.markChunkPendingToSend(chunk);
                Set<ChunkPos> pending = incomplete.get(player);
                if (pending != null) pending.remove(pos);
            }
        }
    }

    private static void tickPlayer(ServerPlayer player)
    {
        int layer = layerIndex(player);
        if (layer < 0)
        {
            //Leaving the stack by warp or teleport, not just by disconnecting, must not leave per-player state
            //behind: the tick counter and the incomplete set are otherwise only cleaned on disconnect.
            if (anchors.containsKey(player) || incomplete.containsKey(player) || ticks.containsKey(player))
                forget(player);
            return;
        }

        keepWindowLoaded(player);

        //The joining player's first chunks are composed before the layers below are loaded, so the lower
        //bands go out as air. Once all three are in, send the whole view again; after that it only has to
        //happen when the window slides.
        if (!windowLoaded(player)) ready.put(player, false);
        else if (!ready.getOrDefault(player, false))
        {
            ready.put(player, true);
            resendChunks(player);
        }

        //A layer is a real dimension, so leaving it by falling or jumping is a real teleport. The client
        //never sees it as such: the layer changed, the offset changed by the opposite amount, and the two
        //cancel out to a one-block step.
        double y = player.getY();
        if (y < 0 && layer > 0)
            teleport(player, layer - 1, y + LAYER_HEIGHT, player.getDeltaMovement());
        else if (y >= LAYER_HEIGHT && layer < LAYERS - 1)
            teleport(player, layer + 1, y - LAYER_HEIGHT, player.getDeltaMovement());

        //Keep the player inside the middle of the window. The slide is triggered a few blocks before the edge
        //rather than at it, so that the seam crossing itself - where the band changes by one and the layer
        //changes by one, cancelling exactly - carries no re-send at all.
        if (band(player) == 0 && player.getY() < SLIDE_BUFFER && anchor(player) > 0)
        {
            anchors.put(player, anchor(player) - 1);
            resendChunks(player);
            resyncPosition(player);
        }
        else if (band(player) == WINDOW_LAYERS - 1 && player.getY() > LAYER_HEIGHT - 1 - SLIDE_BUFFER
                 && anchor(player) < LAYERS - WINDOW_LAYERS)
        {
            anchors.put(player, anchor(player) + 1);
            resendChunks(player);
            resyncPosition(player);
        }

        int tick = ticks.merge(player, 1, Integer::sum);
        if (tick % 20 == 0) healIncomplete(player);
    }

    /**
     * Re-sends columns that were composed while a band was still loading.
     *
     * <p>The chunk-load hook catches most of these, but not all: a layer chunk that finished loading before
     * the player had a window is never seen as an event, and a column can be re-composed by a slide before its
     * lower band has arrived. The sweep is the backstop - once a second, send again anything that is now
     * complete, and forget columns that have left the view.
     */
    private static void healIncomplete(ServerPlayer player)
    {
        java.util.Set<ChunkPos> pending = incomplete.get(player);
        if (pending == null || pending.isEmpty()) return;
        ServerLevel host = (ServerLevel) player.level();
        if (player.connection == null) return;

        for (ChunkPos pos : pending)
        {
            if (!player.getChunkTrackingView().contains(pos))
            {
                pending.remove(pos);
                continue;
            }
            if (!columnsLoaded(player, pos)) continue;
            LevelChunk chunk = host.getChunkSource().getChunkNow(pos.x(), pos.z());
            if (chunk == null) continue;
            player.connection.chunkSender.markChunkPendingToSend(chunk);
            pending.remove(pos);
        }
    }

    private static void teleport(ServerPlayer player, int layer, double y, Vec3 motion)
    {
        ServerLevel target = layer(player.level().getServer(), layer);
        if (target == null) return;
        Vec3 pos = new Vec3(player.getX(), y, player.getZ());
        TeleportTransition transition = new TeleportTransition(target, pos, motion, player.getYRot(), player.getXRot(),
                                                             TeleportTransition.DO_NOTHING);
        //The respawn packet is sent inside this call, synchronously, and the hook cancels it while this is set.
        seamTeleports.add(player);
        try
        {
            player.teleport(transition);
        }
        finally
        {
            seamTeleports.remove(player);
        }
    }

    /**
     * Whether every band of the window has a chunk at this column.
     *
     * <p>Different from {@link #windowLoaded}, which only asks about the player's own column.
     */
    public static boolean columnsLoaded(ServerPlayer player, ChunkPos pos)
    {
        MinecraftServer server = player.level().getServer();
        int anchor = anchor(player);
        for (int band = 0; band < WINDOW_LAYERS; band++)
        {
            ServerLevel level = layer(server, anchor + band);
            if (level == null || level.getChunkSource().getChunkNow(pos.x(), pos.z()) == null) return false;
        }
        return true;
    }

    /** Whether the player's own chunk exists in all three window layers. */
    private static boolean windowLoaded(ServerPlayer player)
    {
        return columnsLoaded(player, player.chunkPosition());
    }

    /**
     * Holds the three window layers around the player's chunk.
     *
     * <p>Composition reads the layer chunks off the server thread's own chunk cache, so the layers below
     * (which no player is standing in) need tickets of their own or they unload and the lower bands turn to
     * air. The radius has to cover the whole view, not just the player's column: every column the client is
     * sent is composed from the same three layers.
     *
     * <p><b>Why {@code PLAYER_LOADING} and not {@code ENDER_PEARL}.</b> {@code ENDER_PEARL} carries a 40-tick
     * timeout, and this method only runs when the player's chunk or the anchor changes - so the tickets expired
     * two seconds after the player stopped moving, the lower layers unloaded, and every column composed after
     * that was missing its bands. That was the "adjacent layer not rendered" report in its most consistent
     * form: it happened whenever the player stood still. {@code PLAYER_LOADING} has no timeout, and it also
     * only loads - the layers nobody is standing in do not run entity or block ticks for a window nobody can
     * reach into.
     *
     * <p>Because it does not expire, the tickets are removed explicitly when the window moves away from them:
     * {@code addTicket} matches on type and level, so the removal is symmetric.
     */
    private static void keepWindowLoaded(ServerPlayer player)
    {
        int radius = viewRadius(player);
        TicketKey key = new TicketKey(player.chunkPosition(), anchor(player), radius);
        if (key.equals(tickets.get(player))) return;

        TicketKey old = tickets.put(player, key);
        if (old != null) releaseTickets(player, old);

        MinecraftServer server = player.level().getServer();
        for (int band = 0; band < WINDOW_LAYERS; band++)
        {
            ServerLevel level = layer(server, key.anchor() + band);
            if (level != null)
                level.getChunkSource().addTicketWithRadius(TicketType.PLAYER_LOADING, key.pos(), key.radius());
        }
    }

    /** Drops the tickets of a window the player has left, so nothing stays loaded on its behalf. */
    private static void releaseTickets(ServerPlayer player, TicketKey key)
    {
        MinecraftServer server = player.level().getServer();
        if (server == null) return;
        for (int band = 0; band < WINDOW_LAYERS; band++)
        {
            ServerLevel level = layer(server, key.anchor() + band);
            if (level != null)
                level.getChunkSource().removeTicketWithRadius(TicketType.PLAYER_LOADING, key.pos(), key.radius());
        }
    }

    /** How far out the window has to be held, in chunks: the whole view, plus the in-flight ring. */
    private static int viewRadius(ServerPlayer player)
    {
        if (player.getChunkTrackingView() instanceof ChunkTrackingView.Positioned view)
            return view.viewDistance() + 2;
        return 10;
    }

    /**
     * A chunk became available in a layer. <b>Called off the server thread.</b>
     *
     * <p>Records only; {@link #tick} does the work. See {@link #loadedColumns} for why that separation is not
     * optional - an earlier version called {@code PlayerChunkSender} from here and raced the server thread.
     */
    public static void onLayerChunkLoaded(ServerLevel level, LevelChunk chunk)
    {
        int layer = layerIndex(level);
        if (layer < 0) return;
        loadedColumns.add(new LayerColumn(layer, chunk.getPos()));
    }

    /**
     * Re-announces every chunk the player tracks.
     *
     * <p>A slide changes what each band contains while the player's own chunk stays where it was, so vanilla's
     * tracking diff never runs - the same trap {@code RandomTransformer.showPage} documents. Re-marking the
     * chunk as pending is what makes the client fetch the new composition.
     */
    private static void resendChunks(ServerPlayer player)
    {
        ServerLevel level = (ServerLevel) player.level();
        if (player.connection == null) return;
        player.getChunkTrackingView().forEach(pos ->
        {
            LevelChunk chunk = level.getChunkSource().getChunkNow(pos.x(), pos.z());
            if (chunk != null) player.connection.chunkSender.markChunkPendingToSend(chunk);
        });
    }

    /**
     * Sends the player's own position again so the client picks up the new offset.
     *
     * <p>The world moved by {@code LAYER_HEIGHT} in window coordinates and the player did not move at all in
     * the layer, so without this the client would keep the old absolute Y and be one layer out.
     */
    private static void resyncPosition(ServerPlayer player)
    {
        if (player.connection == null) return;
        //Not connection.teleport(x,y,z,yaw,pitch): that overload zeroes the motion, which would stop a player
        //mid-fall once per layer. Carrying the current motion keeps the descent continuous.
        player.connection.teleport(new PositionMoveRotation(
                new Vec3(player.getX(), player.getY(), player.getZ()),
                player.getDeltaMovement(),
                player.getYRot(), player.getXRot()), java.util.Set.of());
    }
}
